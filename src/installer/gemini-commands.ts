/**
 * Gemini CLI slash-command renderer (REQ-GEMINI-005).
 *
 * Two renderers, ONE source: the Claude target copies `commands/specship/*.md`
 * verbatim; this module renders the very same files into Gemini CLI's
 * custom-command TOML, so editing a source command changes both surfaces and
 * the two cannot drift. Pure string work — nothing here touches the user's
 * config dirs; `targets/gemini.ts` owns where the output lands.
 *
 * Format provenance (house rule: verified from the installed package, never
 * from memory) — `@google/gemini-cli` **0.28.0**:
 *
 *   - `dist/src/services/FileCommandLoader.js`: globs `**\/*.toml` under each
 *     commands dir; validates with `TomlCommandDefSchema` = `{ prompt: string
 *     (required), description?: string }` (any other key is ignored); the
 *     command name is the path relative to the commands dir minus `.toml`,
 *     segments joined with `:` — so `commands/specship/spec.toml` is invoked
 *     as `/specship:spec`, the same name Claude Code gives
 *     `commands/specship/spec.md`. Parsed with `@iarna/toml` (TOML 0.5).
 *     A project-scope dir is skipped entirely when folder trust is enabled
 *     and the folder is untrusted.
 *   - Commands dirs (`gemini-cli-core` `dist/src/config/storage.js`):
 *     global `Storage.getUserCommandsDir()` = `~/.gemini/commands`, project
 *     `storage.getProjectCommandsDir()` = `<project>/.gemini/commands`.
 *   - Arguments (`prompt-processors/types.js`, `shellProcessor.js`,
 *     `argumentProcessor.js`): `{{args}}` (SHORTHAND_ARGS_PLACEHOLDER) is
 *     replaced with the raw argument string outside `!{…}`; when a prompt has
 *     NO `{{args}}`, the whole raw invocation is appended instead. So Claude's
 *     `$ARGUMENTS` maps 1:1 onto `{{args}}`.
 *   - Injection triggers: `!{…}` runs a shell command and `@{…}` inlines a
 *     file before the prompt is sent. A source body containing either would
 *     execute on Gemini but not on Claude, so such a command is EXCLUDED.
 *   - Built-in tool names (`gemini-cli-core` `dist/src/tools/tool-names.js`):
 *     `read_file`, `write_file`, `replace` (edit), `run_shell_command`,
 *     `ask_user` (registered unconditionally in `config.js`). MCP tools are
 *     exposed to the model under their bare server tool name.
 *
 * Per-command decisions (the REQ-GEMINI-005 `[needs review]` question): the
 * Gemini set is exactly the Claude installer's set (`RETRIEVAL_TIER_COMMANDS`
 * + `GOVERNANCE_TIER_COMMANDS` in `targets/claude.ts`), each passed through
 * the rewrites below and then the Claude-only guard:
 *
 *   - `explore` — INCLUDED. Pure MCP-tool routing; only `mcp__specship__*`
 *     names + `$ARGUMENTS` need rewriting. (No body dispatches the
 *     `specship-explorer` subagent; the guard would exclude one that did.)
 *   - `spec`    — INCLUDED, degraded inline: `Write`/`Edit`/`Read` tool names
 *     → Gemini's; the `designer-loop` skill (a `~/.claude/skills` asset
 *     Gemini doesn't get) → "run the taste loop inline" (the body already
 *     spells the loop out); `claude mcp add` → `gemini mcp add` (verified:
 *     `commands/mcp/add.js` takes `--transport http <name> <url>`). Its
 *     `specship workflow run …` launches are SpecShip CLI calls, host-neutral
 *     from the command's point of view.
 *   - `check`   — INCLUDED. CLI + MCP routing only.
 *   - `learn`   — INCLUDED. Drives the `specship reflect --capture` CLI only.
 *   - `day`     — INCLUDED. JIRA MCP tools (present when installed
 *     `--with-jira`, same as on Claude).
 *   - `jira`    — NOT RENDERED: the Claude installer doesn't ship it either
 *     (plugin-only), so rendering it would widen Gemini past parity.
 *
 * Anything a future source edit introduces that these rewrites don't cover
 * trips `CLAUDE_ONLY_MARKERS`, and that command is excluded with a note —
 * never shipped broken.
 */

import * as fs from 'fs';
import * as path from 'path';

/** First line of every TOML we write — uninstall/overwrite only touch files carrying it. */
export const GEMINI_COMMAND_HEADER_MARKER = '# Generated by specship install — REQ-GEMINI-005.';

/** Gemini's argument placeholder (gemini-cli 0.28.0 SHORTHAND_ARGS_PLACEHOLDER). */
export const GEMINI_ARGS_PLACEHOLDER = '{{args}}';

/**
 * Claude → Gemini rewrites, applied in order to the command body. Each maps a
 * Claude-only construct onto its verified Gemini equivalent.
 */
const REWRITES: ReadonlyArray<readonly [RegExp, string]> = [
  // Claude's argument placeholder → Gemini's.
  [/\$ARGUMENTS\b/g, GEMINI_ARGS_PLACEHOLDER],
  // Gemini exposes MCP tools by bare name.
  [/\bmcp__specship__(\w+)/g, '$1'],
  // Claude built-in tool names → Gemini built-in tool names.
  [/`AskUserQuestion`/g, 'the `ask_user` tool'],
  [/`Write`/g, '`write_file`'],
  [/`Edit`/g, '`replace`'],
  [/`Read`/g, '`read_file`'],
  // The designer-loop skill is a Claude skills-dir asset; the spec body
  // already inlines the loop, so point at that instead.
  [/ and the `designer-loop` skill rather than re-explaining either/g, ' rather than re-explaining it'],
  [
    /Follow the \*\*`designer-loop` skill\*\* \(`~\/\.claude\/skills\/designer-loop\/SKILL\.md`\)\s*—\s*it is the authority\. In brief:/g,
    'Run the taste loop inline:',
  ],
  // `claude mcp add` → the verified Gemini equivalent.
  [/\bclaude mcp add\b/g, 'gemini mcp add'],
];

/**
 * Constructs that have no Gemini equivalent (or that Gemini would interpret
 * differently). Checked AFTER the rewrites; any hit excludes the command.
 */
const CLAUDE_ONLY_MARKERS: ReadonlyArray<readonly [RegExp, string]> = [
  [/\bmcp__\w+__/, 'a Claude-prefixed MCP tool name'],
  [/specship-explorer/, 'the specship-explorer subagent'],
  [/\bsubagent_type\b|`Task`|`Agent`|\bTask tool\b/, 'Claude subagent dispatch'],
  [/\bAskUserQuestion\b|\bTodoWrite\b/, 'a Claude-only built-in tool'],
  [/\.claude\/(skills|agents|commands)\b|`[\w-]+` skill\b/, 'a Claude skill/agent asset'],
  [/\bclaude mcp\b/, 'the `claude mcp` CLI'],
  [/\$ARGUMENTS\b/, 'an unrewritten $ARGUMENTS'],
  [/!\{/, "Gemini's `!{…}` shell-injection trigger"],
  [/@\{/, "Gemini's `@{…}` file-injection trigger"],
];

/** Thrown when a source command cannot be rendered faithfully for Gemini. */
export class GeminiCommandUnsupported extends Error {
  readonly reason: string;
  constructor(reason: string) {
    super(`depends on ${reason}, which Gemini CLI has no equivalent for`);
    this.reason = reason;
  }
}

/** Split `---\nkey: value\n---\nbody` into a flat frontmatter map and the body. */
export function parseCommandMarkdown(source: string): { meta: Record<string, string>; body: string } {
  const text = source.replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n?/.exec(text);
  if (!match) return { meta: {}, body: text };
  const meta: Record<string, string> = {};
  for (const line of (match[1] ?? '').split('\n')) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (!kv || kv[1] === undefined) continue;
    let value = (kv[2] ?? '').trim();
    if (value.length >= 2 && ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'")))) {
      value = value.slice(1, -1);
    }
    meta[kv[1]] = value;
  }
  return { meta, body: text.slice(match[0].length).replace(/^\n+/, '') };
}

/** TOML basic-string escaping (shared by `"…"` and `"""…"""`). */
function escapeTomlBasic(s: string, multiline: boolean): string {
  let out = '';
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += multiline ? '\n' : '\\n';
    else if (ch === '\t') out += multiline ? '\t' : '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += ch;
  }
  return out;
}

/** True when `s` can sit inside a TOML multi-line literal string unchanged. */
function fitsMultilineLiteral(s: string): boolean {
  if (s.includes("'''")) return false;
  // Literal strings allow tab and newline, but no other control character.
  return !/[\u0000-\u0008\u000b-\u001f\u007f]/.test(s);
}

/** Encode a prompt body as a TOML multi-line string value. */
export function tomlMultiline(body: string): string {
  const text = body.endsWith('\n') ? body : `${body}\n`;
  // The newline right after the opening delimiter is trimmed by TOML, and
  // ending on a newline keeps a trailing quote off the closing delimiter.
  return fitsMultilineLiteral(text)
    ? `'''\n${text}'''`
    : `"""\n${escapeTomlBasic(text, true)}"""`;
}

/** Apply the Claude → Gemini rewrites to a command body. */
export function rewriteForGemini(body: string): string {
  return REWRITES.reduce((acc, [pattern, replacement]) => acc.replace(pattern, replacement), body);
}

/**
 * Render one Claude command markdown file into Gemini CLI TOML. Throws
 * `GeminiCommandUnsupported` when the body still depends on Claude-only
 * machinery after the rewrites.
 */
export function renderGeminiCommand(markdownSource: string, sourceName = 'command'): string {
  const { meta, body } = parseCommandMarkdown(markdownSource);
  const prompt = rewriteForGemini(body);
  for (const [pattern, reason] of CLAUDE_ONLY_MARKERS) {
    if (pattern.test(prompt)) throw new GeminiCommandUnsupported(reason);
  }
  const lines = [
    GEMINI_COMMAND_HEADER_MARKER,
    `# Rendered from commands/${sourceName}; edits here are overwritten on reinstall.`,
    '',
  ];
  if (meta.description) lines.push(`description = "${escapeTomlBasic(meta.description, false)}"`);
  lines.push(`prompt = ${tomlMultiline(prompt)}`, '');
  return lines.join('\n');
}

/** One entry of the rendered command set. */
export interface GeminiCommandRender {
  /** Source path relative to the commands dir, e.g. `specship/spec.md`. */
  source: string;
  /** Destination path relative to Gemini's commands dir, e.g. `specship/spec.toml`. */
  target: string;
  /** The TOML file body — absent when the command was excluded. */
  toml?: string;
  /** Why the command was excluded (absent when rendered). */
  excluded?: string;
}

/** `specship/spec.md` → `specship/spec.toml`. */
export function geminiCommandTarget(source: string): string {
  return source.replace(/\.md$/, '.toml');
}

/**
 * Render each named source command under `commandsDir` (the same dir the
 * Claude target copies from). Never throws for an unsupported command — it
 * comes back with `excluded` set so the caller can surface a note.
 */
export function geminiCommandSet(commandsDir: string, names: readonly string[]): GeminiCommandRender[] {
  return names.map((source) => {
    const target = geminiCommandTarget(source);
    const markdown = fs.readFileSync(path.join(commandsDir, source), 'utf-8');
    try {
      return { source, target, toml: renderGeminiCommand(markdown, source) };
    } catch (err) {
      if (err instanceof GeminiCommandUnsupported) return { source, target, excluded: err.message };
      throw err;
    }
  });
}
